"""TetalCut's sound bank, synthesised from nothing: every effect and beat
here is generated by this script (no samples), so the sounds are the
project's own and free to use in any video.

    python3 scripts/tetalcut-sounds.py src/crates/concat/sounds

writes <folder>/<category>/<name>.m4a (AAC, needs ffmpeg) and
<folder>/../src/sounds.rs, the list the app embeds.
"""
import os
import subprocess
import sys
import tempfile
import wave

import numpy as np

SR = 48000
rng = np.random.default_rng(7)


def t(seconds):
    return np.arange(int(SR * seconds)) / SR


def env(n, attack=0.005, release=None, curve=4.0):
    """Attack then exponential-ish decay over n samples."""
    a = max(1, int(SR * attack))
    e = np.ones(n)
    e[:a] = np.linspace(0, 1, a)
    rest = n - a
    if rest > 0:
        x = np.linspace(0, 1, rest)
        e[a:] = (1 - x) ** curve if release is None else np.exp(-x * release)
    return e


def noise(n):
    return rng.uniform(-1, 1, n)


def lowpass(x, cutoff):
    """One-pole lowpass; cutoff may be an array (sweeps)."""
    cutoff = np.broadcast_to(np.asarray(cutoff, dtype=float), x.shape)
    a = np.exp(-2 * np.pi * cutoff / SR)
    y = np.zeros_like(x)
    acc = 0.0
    for i in range(len(x)):
        acc = (1 - a[i]) * x[i] + a[i] * acc
        y[i] = acc
    return y


def highpass(x, cutoff):
    return x - lowpass(x, cutoff)


def bandpass(x, low, high):
    return lowpass(highpass(x, low), high)


def sine_sweep(f0, f1, seconds, curve="exp"):
    n = int(SR * seconds)
    if curve == "exp":
        f = f0 * (f1 / f0) ** np.linspace(0, 1, n)
    else:
        f = np.linspace(f0, f1, n)
    return np.sin(2 * np.pi * np.cumsum(f) / SR)


def norm(x, peak=0.89):
    m = np.max(np.abs(x)) or 1.0
    return x / m * peak


def fade(x, out=0.01, inn=0.002):
    o, i = int(SR * out), int(SR * inn)
    if o:
        x[-o:] *= np.linspace(1, 0, o)
    if i:
        x[:i] *= np.linspace(0, 1, i)
    return x


def mix(*parts):
    n = max(len(p) for p in parts)
    out = np.zeros(n)
    for p in parts:
        out[: len(p)] += p
    return out


def at(x, seconds, total):
    out = np.zeros(int(SR * total))
    s = int(SR * seconds)
    end = min(len(out), s + len(x))
    out[s:end] += x[: end - s]
    return out


# ── effects ────────────────────────────────────────────────────────────


def whoosh(seconds=0.7, low=300, high=4000):
    n = int(SR * seconds)
    shape = np.sin(np.linspace(0, np.pi, n)) ** 2
    sweep = low * (high / low) ** (np.sin(np.linspace(0, np.pi, n)))
    return fade(norm(bandpass(noise(n), sweep * 0.3, sweep) * shape))


def swoosh_fast():
    return whoosh(0.35, 600, 7000)


def riser(seconds=3.0):
    n = int(SR * seconds)
    x = np.linspace(0, 1, n)
    tone = sine_sweep(150, 1200, seconds) + 0.5 * sine_sweep(151.5, 1210, seconds)
    hiss = highpass(noise(n), 200 + 6000 * x) * 0.6
    return fade(norm((tone * 0.5 + hiss) * x ** 2))


def downlifter(seconds=2.0):
    return fade(norm(riser(seconds)[::-1]), out=0.05)


def boom():
    n = int(SR * 1.6)
    body = sine_sweep(120, 35, 1.6) * env(n, 0.002, release=4)
    click = lowpass(noise(n), 3000) * env(n, 0.001, release=60)
    return fade(norm(np.tanh(2.2 * (body + 0.4 * click))))


def hit():
    n = int(SR * 0.9)
    body = sine_sweep(180, 50, 0.9) * env(n, 0.001, release=7)
    snap = bandpass(noise(n), 800, 6000) * env(n, 0.001, release=30)
    return fade(norm(np.tanh(1.8 * (body + 0.7 * snap))))


def bass_drop():
    n = int(SR * 2.5)
    s = sine_sweep(90, 28, 2.5)
    sub = np.tanh(3 * s) * env(n, 0.003, release=1.8)
    return fade(norm(mix(sub, 0.5 * hit())), out=0.2)


def pop():
    n = int(SR * 0.12)
    return fade(norm(sine_sweep(900, 300, 0.12) * env(n, 0.001, release=25)))


def click():
    n = int(SR * 0.05)
    return fade(norm(bandpass(noise(n), 2000, 9000) * env(n, 0.0005, release=80)))


def ding(freq=1318.5, seconds=1.4):
    n = int(SR * seconds)
    x = t(seconds)
    tone = sum(a * np.sin(2 * np.pi * freq * k * x) for k, a in [(1, 1), (2.76, 0.4), (5.4, 0.2)])
    return fade(norm(tone * env(n, 0.002, release=5)))


def notification():
    total = 0.7
    return fade(norm(mix(at(ding(1046.5, 0.5), 0, total), at(ding(1568.0, 0.5), 0.12, total))))


def success():
    total = 1.0
    notes = [523.25, 659.25, 783.99, 1046.5]
    return fade(norm(mix(*[at(ding(f, 0.6), i * 0.09, total) for i, f in enumerate(notes)])))


def error_buzz():
    n = int(SR * 0.45)
    x = t(0.45)
    sq = np.sign(np.sin(2 * np.pi * 140 * x)) * 0.5 + np.sign(np.sin(2 * np.pi * 147 * x)) * 0.5
    gate = (np.sin(2 * np.pi * 9 * x) > -0.3).astype(float)
    return fade(norm(lowpass(sq, 2500) * gate * env(n, 0.005, release=2)))


def cash_register():
    total = 1.4
    bell = ding(2093.0, 1.2) + 0.6 * ding(2637.0, 1.2)
    drawer = bandpass(noise(int(SR * 0.25)), 300, 3000) * env(int(SR * 0.25), 0.002, release=12)
    return fade(norm(mix(at(drawer, 0, total), at(norm(bell) * 0.8, 0.12, total))))


def camera_shutter():
    total = 0.3
    c1 = click()
    c2 = bandpass(noise(int(SR * 0.08)), 1000, 6000) * env(int(SR * 0.08), 0.001, release=40)
    return fade(norm(mix(at(c1, 0, total), at(c2, 0.07, total))))


def typing():
    total = 2.0
    out = np.zeros(int(SR * total))
    when = 0.05
    while when < total - 0.1:
        k = bandpass(noise(int(SR * 0.04)), 1500, 8000) * env(int(SR * 0.04), 0.0005, release=70)
        out += at(k * rng.uniform(0.5, 1.0), when, total)
        when += rng.uniform(0.07, 0.18)
    return fade(norm(out), out=0.05)


def boing():
    n = int(SR * 0.8)
    x = t(0.8)
    f = 220 + 160 * np.sin(2 * np.pi * 7 * x) * np.exp(-x * 4)
    return fade(norm(np.sin(2 * np.pi * np.cumsum(f) / SR) * env(n, 0.002, release=4)))


def record_scratch():
    n = int(SR * 0.6)
    x = t(0.6)
    speed = np.abs(np.sin(2 * np.pi * 3.2 * x)) * 2600 + 300
    return fade(norm(bandpass(noise(n), speed * 0.4, speed) * env(n, 0.002, release=2)))


def laser():
    n = int(SR * 0.35)
    return fade(norm(sine_sweep(2400, 300, 0.35) * env(n, 0.001, release=8)))


def glitch():
    total = 0.6
    out = np.zeros(int(SR * total))
    when = 0.0
    while when < total - 0.05:
        d = rng.uniform(0.015, 0.06)
        m = int(SR * d)
        kind = rng.integers(3)
        if kind == 0:
            seg = np.sign(np.sin(2 * np.pi * rng.uniform(80, 900) * t(d)))
        elif kind == 1:
            seg = noise(m)
        else:
            seg = np.zeros(m)
        out += at(seg * 0.8, when, total)
        when += d
    return fade(norm(lowpass(out, 7000), 0.55))


def heartbeat():
    total = 1.8

    def beat():
        n = int(SR * 0.18)
        return sine_sweep(70, 40, 0.18) * env(n, 0.003, release=12)

    return fade(norm(mix(at(beat(), 0.05, total), at(beat() * 0.7, 0.33, total),
                         at(beat(), 0.95, total), at(beat() * 0.7, 1.23, total))))


def drum_roll():
    total = 2.2
    out = np.zeros(int(SR * total))
    when = 0.0
    while when < total - 0.4:
        out += at(snare_hit() * (0.4 + 0.6 * when / total), when, total)
        when += 0.045
    out += at(crash() * 0.9, total - 0.4, total)
    return fade(norm(out), out=0.2)


def tick_tock():
    total = 2.0
    out = np.zeros(int(SR * total))
    for i in range(4):
        f = 1800 if i % 2 == 0 else 1300
        n = int(SR * 0.04)
        out += at(np.sin(2 * np.pi * f * t(0.04)) * env(n, 0.0005, release=50), i * 0.5, total)
    return fade(norm(out))


def magic():
    total = 1.6
    out = np.zeros(int(SR * total))
    for i in range(14):
        f = 1200 * 2 ** (rng.uniform(0, 2))
        out += at(ding(f, 0.5) * 0.4, i * 0.07, total)
    return fade(norm(out), out=0.2)


def phone_vibrate():
    total = 1.0
    x = t(total)
    buzz = np.sin(2 * np.pi * 160 * x) * (np.sin(2 * np.pi * 2 * x) > 0)
    return fade(norm(lowpass(np.tanh(3 * buzz), 900), 0.45))


# ── drums for the beats ─────────────────────────────────────────────────


def kick(pitch=1.0):
    n = int(SR * 0.45)
    body = sine_sweep(150 * pitch, 42 * pitch, 0.45) * env(n, 0.001, release=7)
    return np.tanh(2.5 * body)


def snare_hit():
    n = int(SR * 0.22)
    tone = np.sin(2 * np.pi * 190 * t(0.22)) * env(n, 0.001, release=20)
    rattle = bandpass(noise(n), 1500, 9000) * env(n, 0.001, release=14)
    return 0.5 * tone + 0.8 * rattle


def clap():
    n = int(SR * 0.25)
    x = bandpass(noise(n), 900, 5000)
    e = env(n, 0.001, release=14)
    for off in (0.01, 0.02):
        o = int(SR * off)
        e[o:] += env(n - o, 0.001, release=30) * 0.6
    return x * e


def hat(open_=False):
    d = 0.3 if open_ else 0.06
    n = int(SR * d)
    return highpass(noise(n), 7000) * env(n, 0.0005, release=8 if open_ else 45) * 0.5


def crash():
    n = int(SR * 1.5)
    return highpass(noise(n), 4000) * env(n, 0.001, release=3) * 0.6


def bass_note(freq, seconds):
    n = int(SR * seconds)
    x = t(seconds)
    s = np.sin(2 * np.pi * freq * x) + 0.3 * np.sin(2 * np.pi * 2 * freq * x)
    return np.tanh(1.5 * s) * env(n, 0.005, release=2.5)


def pad(freqs, seconds):
    n = int(SR * seconds)
    x = t(seconds)
    s = np.zeros(n)
    for f in freqs:
        for det in (-0.6, 0.0, 0.6):
            s += np.sin(2 * np.pi * (f + det) * x + rng.uniform(0, 6.28))
    a = int(SR * 0.3)
    e = np.ones(n)
    e[:a] = np.linspace(0, 1, a)
    e[-a:] = np.linspace(1, 0, a)
    return lowpass(s, 1800) * e


def note(name):
    names = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6, "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11}
    letter = name[:-1]
    octave = int(name[-1])
    return 440.0 * 2 ** ((names[letter] - 9 + 12 * (octave - 4)) / 12)


def chord(root, kind="m"):
    r = note(root)
    third = 3 if kind == "m" else 4
    return [r, r * 2 ** (third / 12), r * 2 ** (7 / 12)]


def beat(bpm, bars, pattern, progression, bass_pattern, swing=0.0, pad_level=0.12):
    """A loop of `bars` bars of 16 steps: pattern maps a drum to its steps."""
    step = 60.0 / bpm / 4
    total = bars * 16 * step + 0.6
    out = np.zeros(int(SR * total))
    drums = {"k": lambda: kick(), "s": snare_hit, "c": clap, "h": lambda: hat(False), "o": lambda: hat(True)}
    for bar in range(bars):
        for drum, steps in pattern.items():
            for s in steps:
                when = (bar * 16 + s) * step + (swing * step if s % 2 else 0.0)
                gain = 1.0 if drum == "k" else 0.7
                out += at(drums[drum]() * gain, when, total)
        root = progression[bar % len(progression)]
        out += at(pad(chord(root[0] + "4", root[1]), 16 * step) * pad_level, bar * 16 * step, total)
        for s, length in bass_pattern:
            f = note(root[0] + "2")
            out += at(bass_note(f, length * step) * 0.55, (bar * 16 + s) * step, total)
    out = np.tanh(1.3 * out / (np.max(np.abs(out)) or 1))
    return fade(norm(out, 0.85), out=0.5)


def dembow():
    return beat(95, 12,
                {"k": [0, 4, 8, 12], "s": [3, 6, 11, 14], "h": [0, 2, 4, 6, 8, 10, 12, 14]},
                [("A", "m"), ("F", ""), ("C", ""), ("G", "")],
                [(0, 3), (6, 2), (8, 3), (14, 2)])


def house():
    return beat(124, 16,
                {"k": [0, 4, 8, 12], "c": [4, 12], "o": [2, 6, 10, 14], "h": [1, 3, 5, 7, 9, 11, 13, 15]},
                [("F", "m"), ("D#", ""), ("C#", ""), ("C", "")],
                [(2, 1), (6, 1), (10, 1), (14, 1)])


def trap():
    return beat(140, 16,
                {"k": [0, 7, 10], "c": [8], "h": [0, 2, 3, 4, 6, 8, 10, 11, 12, 13, 14, 15]},
                [("C", "m"), ("G#", ""), ("D#", ""), ("A#", "")],
                [(0, 6), (7, 3), (10, 6)])


def lofi():
    return beat(82, 10,
                {"k": [0, 7, 10], "s": [4, 12], "h": [0, 2, 4, 6, 8, 10, 12, 14]},
                [("D", "m"), ("G", ""), ("C", ""), ("A", "m")],
                [(0, 4), (10, 4)], swing=0.25, pad_level=0.2)


def pop_beat():
    return beat(110, 14,
                {"k": [0, 6, 8], "c": [4, 12], "h": [0, 2, 4, 6, 8, 10, 12, 14]},
                [("C", ""), ("G", ""), ("A", "m"), ("F", "")],
                [(0, 2), (6, 2), (8, 2), (12, 2)])


def chill_corporate():
    return beat(100, 12,
                {"k": [0, 8], "c": [4, 12], "h": [2, 6, 10, 14]},
                [("G", ""), ("D", ""), ("E", "m"), ("C", "")],
                [(0, 4), (8, 4)], pad_level=0.22)


