def slug(text):
    keep = "abcdefghijklmnopqrstuvwxyz0123456789"
    table = str.maketrans("áéíóúñ", "aeioun")
    return "".join(c if c in keep else "-" for c in text.lower().translate(table)).strip("-").replace("--", "-")


def main():
    out = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "sounds")
    os.makedirs(out, exist_ok=True)
    rows = []
    for category, name, make in SOUNDS:
        samples = make()
        pcm = (np.clip(samples, -1, 1) * 32767).astype("<i2")
        rel = f"{slug(category)}/{slug(name)}.m4a"
        path = os.path.join(out, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
            with wave.open(tmp.name, "wb") as w:
                w.setnchannels(1)
                w.setsampwidth(2)
                w.setframerate(SR)
                w.writeframes(pcm.tobytes())
            subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp.name, "-c:a", "aac",
                            "-b:a", "128k", "-movflags", "+faststart", path], check=True)
            os.unlink(tmp.name)
        rows.append((category, name, rel, len(samples) / SR))
        print(f"{rel}  {len(samples) / SR:.1f}s  {os.path.getsize(path) // 1024} KB")
    rs = os.path.join(os.path.dirname(out), "src", "sounds.rs")
    with open(rs, "w") as f:
        f.write("// SPDX-License-Identifier: AGPL-3.0-or-later\n")
        f.write("// SPDX-FileCopyrightText: 2026 AJ Media Studio (TetalCut, a fork of Concat)\n\n")
        f.write("//! TetalCut's built-in sound bank, written by scripts/tetalcut-sounds.py:\n")
        f.write("//! every sound synthesised by that script, so free to use in any video.\n\n")
        f.write("/// (category, name, file name, seconds, bytes)\n")
        f.write("pub const BUILT_IN: &[(&str, &str, &str, f64, &[u8])] = &[\n")
        for category, name, rel, seconds in rows:
            f.write(f'    ("{category}", "{name}", "{rel}", {seconds:.2f}, include_bytes!("../sounds/{rel}")),\n')
        f.write("];\n")
    print("wrote", rs)


if __name__ == "__main__":
    main()
